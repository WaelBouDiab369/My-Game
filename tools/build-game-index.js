// Builds shared/games-index.js: every playable game with its link and its name and description in English, Arabic and French.
// Run after adding or renaming a game:   node tools/build-game-index.js
const fs = require("fs"), path = require("path"), vm = require("vm");
const ROOT = path.join(__dirname, "..");
const games = {};

// 1. Science and math games: each file calls MQ.register({ id, title, tag, ... }).
for (const subject of ["math", "chemistry", "physics", "biology"]) {
  const dir = path.join(ROOT, subject, "games");
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".js")).sort()) {
    let def = null;
    const ctx = { window: {}, MQ: { register: (d) => (def = d), draw: {}, tr: (o) => o.en }, BIO: {}, CHEM: {}, PHYS: {}, console, Math, Path2D: function () {} };
    ctx.window = ctx; ctx.window.CHEM = new Proxy({}, { get: () => new Proxy(() => ({}), { get: () => ({}) }) });
    try { vm.runInNewContext(fs.readFileSync(path.join(dir, f), "utf8"), ctx); } catch (e) { /* games only define data at load time */ }
    if (!def) { console.warn("no game found in", subject, f); continue; }
    games[`${subject}:${def.id}`] = { url: `${subject}/play.html?g=${def.id}`, title: def.title, tag: def.tag || null, from: subject };
  }
}

// 2. Geography: the countries game modes and the 14 map topics, named as on the Geography page.
const html = fs.readFileSync(path.join(ROOT, "geography/index.html"), "utf8");
const block = html.slice(html.indexOf("const T = {"), html.indexOf("};", html.indexOf("const T = {")) + 2);
const T = vm.runInNewContext(block.replace("const T =", "T =") + "; T", {});
const tri = (k, i = 0) => ({ en: T.en.t[k][i], ar: T.ar.t[k][i], fr: T.fr.t[k][i] });
const modes = { countries: "find", capitals: "capital", flags: "flag" };
for (const [k, m] of Object.entries(modes)) games[`geo:${k}`] = { url: `geography/world/?mode=${m}`, title: tri(k), tag: tri(k, 1), from: "geography" };
games["geo:study"] = { url: "geography/world/?mode=study", title: { en: "Study the world map", ar: "ادرس خريطة العالم", fr: "Étudie la carte du monde" }, tag: { en: "Tap any country to see its flag, capital and name.", ar: "اضغط على أي دولة لترى علمها وعاصمتها واسمها.", fr: "Touche un pays pour voir son drapeau, sa capitale et son nom." }, from: "geography" };
for (const k of ["continents", "oceans", "seas", "straits", "rivers", "lakes", "islands", "archipelagos", "deserts", "ranges", "mountains", "regions", "cities", "latlong"])
  games[`geo:${k}`] = { url: `geography/explore/?t=${k}`, title: tri(k), tag: tri(k, 1), from: "geography" };

const out = `// Generated by tools/build-game-index.js: every playable game with its link, name and description (EN/AR/FR). Do not edit by hand.\nwindow.ZV_GAMES = ${JSON.stringify(games, null, 1)};\n`;
fs.writeFileSync(path.join(ROOT, "shared/games-index.js"), out);
console.log(Object.keys(games).length, "games written to shared/games-index.js");
